Lang SystemLang() {
    int n = 0;
    SDL_Locale** locales = SDL_GetPreferredLocales(&n);
    Lang l = Lang::En;
    if (locales && n > 0 && locales[0] && locales[0]->language) {
        if (!std::strcmp(locales[0]->language, "pt")) l = Lang::Pt;
        else if (!std::strcmp(locales[0]->language, "es")) l = Lang::Es;
    }
    SDL_free(locales);
    return l;
}

